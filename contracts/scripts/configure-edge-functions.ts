import * as fs from "fs";
import * as path from "path";

/**
 * Generates the configuration file for Lovable edge functions
 * Run this after deploying contracts to update your backend
 */
async function main() {
  const networks = ["mainnet", "arbitrum", "polygon", "bsc"];
  const deploymentsDir = path.join(__dirname, "../deployments");
  
  const config: Record<string, any> = {};

  console.log("\n📋 Generating Edge Function Configuration\n");

  for (const network of networks) {
    const regularFile = path.join(deploymentsDir, `${network}.json`);
    const gaslessFile = path.join(deploymentsDir, `${network}-gasless.json`);
    
    let deployment = null;
    
    if (fs.existsSync(regularFile)) {
      deployment = JSON.parse(fs.readFileSync(regularFile, "utf-8"));
    } else if (fs.existsSync(gaslessFile)) {
      deployment = JSON.parse(fs.readFileSync(gaslessFile, "utf-8"));
    }

    if (deployment) {
      const contracts = deployment.contracts || {
        flashArbExecutor: deployment.flashArbExecutor,
        gaslessRelayer: deployment.gaslessRelayer,
        positionRebalancer: deployment.positionRebalancer,
      };

      config[network] = {
        chainId: deployment.chainId,
        contracts: {
          flashArbExecutor: contracts.flashArbExecutor,
          gaslessRelayer: contracts.gaslessRelayer,
          positionRebalancer: contracts.positionRebalancer,
        },
        deployedAt: deployment.timestamp,
      };
      
      console.log(`✅ ${network}: Found deployment`);
    } else {
      console.log(`⚠️  ${network}: No deployment found`);
    }
  }

  // Generate TypeScript config for edge functions
  const tsConfig = `// Auto-generated by configure-edge-functions.ts
// DO NOT EDIT MANUALLY - Run: npm run configure-edge-functions

export const CONTRACT_ADDRESSES = ${JSON.stringify(config, null, 2)} as const;

export type NetworkName = keyof typeof CONTRACT_ADDRESSES;

export function getContractAddress(
  network: NetworkName,
  contract: 'flashArbExecutor' | 'gaslessRelayer' | 'positionRebalancer'
): string {
  const networkConfig = CONTRACT_ADDRESSES[network];
  if (!networkConfig) {
    throw new Error(\`Network \${network} not deployed\`);
  }
  return networkConfig.contracts[contract];
}
`;

  // Save to edge functions shared directory
  const edgeFunctionsDir = path.join(__dirname, "../../supabase/functions/_shared");
  if (!fs.existsSync(edgeFunctionsDir)) {
    fs.mkdirSync(edgeFunctionsDir, { recursive: true });
  }

  const outputFile = path.join(edgeFunctionsDir, "contract-addresses.ts");
  fs.writeFileSync(outputFile, tsConfig);

  console.log(`\n💾 Configuration saved to: ${outputFile}`);
  console.log("\n📝 Update your edge functions to import from:");
  console.log('   import { getContractAddress } from "../_shared/contract-addresses.ts";\n');
}

main().catch(console.error);
